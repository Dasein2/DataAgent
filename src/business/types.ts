import { z } from "zod";

export const Id = z.string().regex(/^[a-z][a-z0-9_]{0,39}$/);
const identifier = z.string().regex(/^[\p{L}_][\p{L}\p{N}_]{0,63}$/u);
const note = z.string().trim().min(1).max(500);
const label = z.string().trim().min(1).max(100);
const aliases = z.array(label).max(20).default([]);
export const Day = z.iso.date().refine(s => s >= "1900-01-01" && s < "9999-01-01", "Date outside supported range");
const Zone = z.string().max(80).regex(/^(?:UTC|[A-Za-z_]+(?:\/[A-Za-z0-9_+-]+)+)$/).refine(s => {
  try { new Intl.DateTimeFormat("en", { timeZone: s }); return true; } catch { return false; }
}, "Invalid business timezone");
export const Window = z.strictObject({ start: Day, end: Day }).refine(w => w.start < w.end && days(w) <= 366, "Use [start,end) with at most 366 days");
export const days = (w: { start: string; end: string }) => (Date.parse(w.end) - Date.parse(w.start)) / 86_400_000;
// Doris literals are generated by the dialect. Do not accept backslash/control characters.
const scalar = z.union([z.string().max(160).refine(s => !/[\\\x00-\x1f\x7f]/.test(s)), z.number().int().safe()]);
const constant = z.strictObject({ field: identifier, value: scalar });
export const BusinessTable = z.strictObject({
  id: Id, schema: identifier, name: identifier, label, aliases,
  grain: note, level: z.enum(["detail", "aggregate", "dimension"]), keys: z.array(identifier).min(1).max(8),
  time: z.strictObject({ field: identifier, storage: z.enum(["business_date", "utc_datetime"]) }).optional(),
  ingestTime: identifier.optional(), partition: identifier.optional(),
  completeFrom: Day.optional(), completeThrough: Day.optional(),
  fields: z.array(z.strictObject({ column: identifier, label, aliases })).max(50).default([]),
});
const check = z.strictObject({
  window: Window, source: note, checkedAt: z.iso.datetime(), inputRows: z.number().int().positive().safe(),
  outputRows: z.number().int().nonnegative().safe(), factKeysBefore: z.number().int().positive().safe(),
  factKeysAfter: z.number().int().nonnegative().safe(), duplicateKeys: z.number().int().nonnegative().safe(),
  unmatchedRows: z.number().int().nonnegative().safe(), measureReconciled: z.boolean().default(false),
});
export const BusinessRelation = z.strictObject({
  id: Id, from: Id, to: Id, fromFields: z.array(identifier).min(1).max(8), toFields: z.array(identifier).min(1).max(8),
  cardinality: z.enum(["one_to_one", "many_to_one", "one_to_many", "many_to_many"]),
  use: z.enum(["current_dimension", "event_dimension", "preaggregate_fact"]),
  purpose: note, source: note, metrics: z.array(Id).min(1).max(24), check: check.optional(),
});
const measure = z.discriminatedUnion("kind", [
  z.strictObject({ kind: z.literal("count") }),
  z.strictObject({ kind: z.literal("sum"), field: identifier }),
  z.strictObject({ kind: z.literal("distinct"), field: identifier }),
  z.strictObject({ kind: z.literal("ratio"), numerator: constant, unitMultiplier: z.union([z.literal(1), z.literal(100)]).default(1) }),
  z.strictObject({ kind: z.literal("net"), field: identifier, deduction: identifier, relation: Id, filters: z.array(constant).max(8).default([]) }),
]);
export const BusinessMetric = z.strictObject({
  id: Id, label, aliases, owner: label, definition: note, unit: label, table: Id,
  measure, filters: z.array(constant).max(8).default([]),
  allowedFilters: z.array(z.strictObject({ id: Id, field: identifier, label })).max(8).default([]),
  dimensions: z.array(z.strictObject({ id: Id, label, field: identifier, relation: Id.optional(), additive: z.boolean().default(false) })).max(8).default([]),
  visualization: z.enum(["number", "trend_breakdown"]).default("number"),
});
export const CatalogDraft = z.strictObject({
  domain: label, timezone: Zone, tables: z.array(BusinessTable).min(1).max(30),
  relations: z.array(BusinessRelation).max(40).default([]), metrics: z.array(BusinessMetric).min(1).max(24),
});
export type CatalogDraft = z.infer<typeof CatalogDraft>;
export type BusinessTable = z.infer<typeof BusinessTable>;
export type BusinessMetric = z.infer<typeof BusinessMetric>;
export type BusinessRelation = z.infer<typeof BusinessRelation>;
export type Window = z.infer<typeof Window>;
export type CatalogVersion = { id: string; at: string; catalog: CatalogDraft; reviewer?: string; binding?: Record<string, string> };

export const MetricRequest = z.strictObject({
  metric_id: Id, dimension: Id.optional(), grain: z.enum(["period", "day"]).default("period"),
  window: Window, comparison: Window.optional(), filters: z.array(z.strictObject({ id: Id, value: scalar })).max(8).default([]),
});
export type MetricRequest = z.infer<typeof MetricRequest>;
export type VerificationStatus = "verified" | "limited" | "unconfirmed";
export interface BusinessEvidence {
  domain: string;
  version: string;
  reviewer: string;
  timezone: string;
  metric: Pick<BusinessMetric, "id" | "label" | "unit" | "definition" | "owner" | "visualization">;
  request: MetricRequest;
  measure?: BusinessMetric["measure"]["kind"];
  ratio_multiplier?: 1 | 100;
  deduction_details?: boolean;
  available_dimensions?: Array<{ id: string; label: string }>;
  dimension?: { id: string; label: string; additive: boolean };
  relations: BusinessRelation[];
  tables: Array<Pick<BusinessTable, "schema" | "name" | "grain" | "keys" | "time">>;
  complete_from?: string;
  complete_through?: string;
  status: VerificationStatus;
  reasons: string[];
}

export const resultValueRef = (id: string, row: number, column: number) => `${id}#row=${row}&col=${column}`;
export function parseResultValueRef(ref: string) {
  const m = /^(res_[a-z0-9]{8,40})#row=(\d{1,8})&col=(\d{1,4})$/.exec(ref);
  return m ? { id: m[1]!, row: Number(m[2]), column: Number(m[3]) } : undefined;
}
